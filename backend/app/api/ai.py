from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.auth.security import get_current_user
from app.db.database import get_db
from app.models.conversation import Conversation
from app.models.generated_code import GeneratedCode
from app.models.prompt import Prompt
from app.models.project import Project
from app.models.user import User
from app.schemas.generated_code import GeneratedCodeResponse
from app.schemas.prompt import PromptRequest, PromptResponse
from app.schemas.conversation import ConversationCreate, ConversationResponse
from app.services.ai_service import AIService

router = APIRouter(prefix="/ai", tags=["ai"])


@router.post("/chat", response_model=dict)
def chat_with_ai(
    payload: dict[str, str],
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> dict[str, str]:
    """Handle a chat request and persist the prompt and a simple generated response."""
    project_id = int(payload.get("project_id", 0))
    project = db.get(Project, project_id)
    if not project or project.owner_id != current_user.id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Project not found")

    conversation = db.query(Conversation).filter(Conversation.project_id == project_id).first()
    if conversation is None:
        conversation = Conversation(title="Chat", project_id=project_id)
        db.add(conversation)
        db.commit()
        db.refresh(conversation)

    prompt = Prompt(conversation_id=conversation.id, content=payload.get("message", ""))
    db.add(prompt)
    db.commit()
    db.refresh(prompt)

    response_text = AIService.generate_response(payload.get("message", ""))
    generated_code = GeneratedCode(
        conversation_id=conversation.id,
        language="text",
        code=response_text,
        explanation="Auto-generated response",
    )
    db.add(generated_code)
    db.commit()

    return {"response": response_text}


@router.post("/generate", response_model=GeneratedCodeResponse)
def generate_code(
    payload: dict[str, str],
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
) -> GeneratedCode:
    """Generate code content for a prompt and persist it."""
    project_id = int(payload.get("project_id", 0))
    project = db.get(Project, project_id)
    if not project or project.owner_id != current_user.id:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Project not found")

    conversation = db.query(Conversation).filter(Conversation.project_id == project_id).first()
    if conversation is None:
        conversation = Conversation(title="Generate", project_id=project_id)
        db.add(conversation)
        db.commit()
        db.refresh(conversation)

    code = AIService.generate_code(payload.get("prompt", ""))
    generated = GeneratedCode(
        conversation_id=conversation.id,
        language=payload.get("language", "python"),
        code=code,
        explanation="Generated by AI service",
    )
    db.add(generated)
    db.commit()
    db.refresh(generated)
    return generated
